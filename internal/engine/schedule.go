// applySchedule creates or updates (upsert by name) the DBOS schedule.
// Ticks use the DBOS internal queue: the deploy queue is partitioned and does not dequeue
// workflows without a partition key. The deploy enqueued by the tick uses the deploy queue.
func (e *Engine) applySchedule(req Request) (*Submission, error) {
	// Runs do not belong to the trace of the request that created the schedule.
	req.TraceParent = ""
	d := req.Descriptor
	name := d.ScheduleName()
	err := dbos.ApplySchedules(e.client, []dbos.ScheduleSpec{{
		ScheduleName: name,
		WorkflowName: scheduledWorkflowName,
		Schedule:     d.Schedule.CronExpr(),
		CronTimezone: d.Schedule.Timezone,
		Context:      scheduleContext{Request: req, QueueName: e.queueName},
	}})
	if err != nil {
		return nil, err
	}
	e.logger.Info("schedule di deploy applicata", "schedule", name, "cron", d.Schedule.CronExpr(), "application", d.Application, "environment", d.Environment, "requested_by", req.RequestedBy)
	return &Submission{State: StateScheduled, Schedule: name}, nil
}

// scheduleContext is the value saved in the DBOS schedule and passed to every tick.
type scheduleContext struct {
	Request   Request `json:"request"`
	QueueName string  `json:"queue_name"`
}

// scheduledWorkflow is invoked by DBOS at every schedule tick: it enqueues a deploy with the
// deterministic ID "<schedule>@<tick time>", so a tick never produces two deploys even if
// several workers run it. It does not wait for the deploy, so as not to take a queue slot.
func (w *Worker) scheduledWorkflow(ctx dbos.Context, in dbos.ScheduledWorkflowInput) (string, error) {
	sc, err := dbos.DecodeScheduleContext[scheduleContext](in)
	if err != nil {
		return "", fmt.Errorf("invalid schedule context: %w", err)
	}
	req := sc.Request
	d := &req.Descriptor
	id := scheduledIDPrefix(d.ScheduleName()) + in.ScheduledTime.UTC().Format("20060102T150405Z")
	// The schedule's deploys count as requested by whoever created it. Schedules created with
	// a governance decision evaluate the policy in force at every run, in a DBOS step; the older
	// ones keep the obligations of the schedule's creation.
	if req.Policy != nil && w.governance != nil {
		tp, err := dbos.RunAsStep(ctx, func(c context.Context) (tickPolicy, error) {
			return w.evaluateTick(c, req, in.ScheduledTime)
		}, dbos.WithStepName("policy"), dbos.WithStepMaxRetries(policyStepRetries))
		if err != nil {
			return "", err
		}
		if tp.Deny != "" {
			w.logger.Warn("esecuzione della schedule rifiutata dalla policy di governance", "schedule", d.ScheduleName(), "deployment", id, "reason", tp.Deny)
			return "", fmt.Errorf("run %s not enqueued: %s", id, tp.Deny)
		}
		req.Approval, req.Change, req.Policy = tp.Approval, tp.Change, tp.Policy
	}
	if needsApproval(req) {
		if err := enqueueApproval(ctx, sc.QueueName, req, id); err != nil {
			return "", err
		}
		return id, nil
	}
	h, err := dbos.Enqueue[Result](ctx, deployQueue(req, sc.QueueName), workflowName, req, deployOptions(req, id)...)
	if err != nil {
		return "", err
	}
	return h.GetWorkflowID(), nil
}

// scheduledIDPrefix is the prefix of the IDs of the deploys generated by a schedule.
func scheduledIDPrefix(schedule string) string {
	return schedule + "@"
}

// ListSchedules lists the deploy schedules.
func (e *Engine) ListSchedules(_ context.Context) ([]ScheduleInfo, error) {
	ss, err := dbos.ListSchedules(e.client, dbos.WithScheduleWorkflowNames(scheduledWorkflowName))
	if err != nil {
		return nil, err
	}
	out := make([]ScheduleInfo, 0, len(ss))
	for _, s := range ss {
		out = append(out, toScheduleInfo(s))
	}
	return out, nil
}

// GetSchedule returns a schedule by name.
func (e *Engine) GetSchedule(ctx context.Context, name string) (*ScheduleInfo, error) {
	ss, err := dbos.ListSchedules(e.client, dbos.WithScheduleWorkflowNames(scheduledWorkflowName), dbos.WithScheduleNames(name))
	if err != nil {
		return nil, err
	}
	if len(ss) == 0 {
		return nil, fmt.Errorf("%w: schedule %s", ErrNotFound, name)
	}
	info := toScheduleInfo(ss[0])
	return &info, nil
}

// PauseSchedule suspends the schedule's ticks.
func (e *Engine) PauseSchedule(ctx context.Context, name string) error {
	return e.scheduleOp(ctx, name, "sospesa", dbos.PauseSchedule)
}

// ResumeSchedule reactivates a paused schedule.
func (e *Engine) ResumeSchedule(ctx context.Context, name string) error {
	return e.scheduleOp(ctx, name, "riattivata", dbos.ResumeSchedule)
}

// DeleteSchedule deletes the schedule; deploys already enqueued are not touched.
func (e *Engine) DeleteSchedule(ctx context.Context, name string) error {
	return e.scheduleOp(ctx, name, "eliminata", dbos.DeleteSchedule)
}

// scheduleOp checks that the schedule exists and runs the given operation.
func (e *Engine) scheduleOp(ctx context.Context, name, verb string, op func(dbos.Client, string) error) error {
	if _, err := e.GetSchedule(ctx, name); err != nil {
		return err
	}
	if err := op(e.client, name); err != nil {
		return err
	}
	e.logger.Info("schedule di deploy "+verb, "schedule", name)
	return nil
}

// toScheduleInfo extracts the descriptor data from the schedule context.
func toScheduleInfo(s dbos.WorkflowSchedule) ScheduleInfo {
	info := ScheduleInfo{
		Name:        s.ScheduleName,
		Cron:        strings.TrimSpace(s.Schedule),
		Timezone:    s.CronTimezone,
		Status:      string(s.Status),
		LastFiredAt: s.LastFiredAt,
	}
	if sc, err := dbos.DecodeScheduleContext[scheduleContext](dbos.ScheduledWorkflowInput{Context: s.Context}); err == nil {
		info.Tenant = tenantOf(&sc.Request.Descriptor)
		info.Application = sc.Request.Descriptor.Application
		info.Environment = sc.Request.Descriptor.Environment
		info.RequestedBy = sc.Request.RequestedBy
	}
	return info
}
